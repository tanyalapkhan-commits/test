if __name__ == '__main__':
    with open(os.path.join(THEME, 'photo-plan.json'), encoding='utf-8') as fh:
        old = json.load(fh)
    plan = {
        'format': old['format'],
        'style': old['style'],
        'source': 'Полотна, присланные заказчиком (20 шт.), разложены по слотам вручную — tools/canvas_map.py',
        'canvases': [
            {'id': n, 'theme': theme, 'photos': [{'slot': s, 'alt': a, 'scene': a} for s, a in photos]}
            for n, theme, photos in CANVASES
        ],
    }
    slots = [p['slot'] for c in plan['canvases'] for p in c['photos']]
    assert len(slots) == 120 and len(set(slots)) == 120, 'Нужно 120 уникальных слотов'
    for k, v in ALIASES.items():
        assert v in slots, 'Алиас %s ведёт на несуществующий слот %s' % (k, v)
        assert k not in slots, 'Алиас %s совпадает с реальным слотом' % k
    with open(os.path.join(THEME, 'photo-plan.json'), 'w', encoding='utf-8') as fh:
        json.dump(plan, fh, ensure_ascii=False, indent=1)
    with open(os.path.join(THEME, 'photo-aliases.json'), 'w', encoding='utf-8') as fh:
        json.dump(ALIASES, fh, ensure_ascii=False, indent=1, sort_keys=True)
    print('OK: 120 слотов, алиасов: %d' % len(ALIASES))
